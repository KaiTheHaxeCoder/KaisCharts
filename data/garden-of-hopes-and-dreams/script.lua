function onStepHit()
    if curStep == 64 then
        doTweenZoom('zoom', 'hud', 2, 3, 'sineInOut')
    end
    if curStep == 88 then
        doTweenZoom('zoom', 'hud', 0.75, 1, 'sineInOut')
    end
    if curStep == 96 then
        doTweenZoom('zoom', 'hud', 1, 0.1, 'sineInOut')
    end

    if curStep == 124 then
        doTweenZoom('zoom', 'hud', 2, 3, 'sineInOut')
    end
    if curStep == 152 then
        doTweenZoom('zoom', 'hud', 0.5, 1, 'sineInOut')
    end
    if curStep == 158 then
        doTweenZoom('zoom', 'hud', 1, 0.1, 'sineInOut')
    end
end